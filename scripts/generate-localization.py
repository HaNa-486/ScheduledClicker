"""Generate dependency-free native catalogs from the shared UTF-8 TSV."""
import json
import pathlib
import re
import sys

root = pathlib.Path(__file__).resolve().parents[1]
rows = []
seen = set()
for line in (root / 'localization/ui.tsv').read_text(encoding='utf-8').splitlines():
    if not line or line.startswith('#'):
        continue
    cells = line.split('\t')
    assert len(cells) == 5 and all(cells), f'Invalid catalog row: {line}'
    assert cells[0] not in seen, f'Duplicate key: {cells[0]}'
    seen.add(cells[0])
    placeholders = sorted(re.findall(r'\{\d+\}', cells[0]))
    for cell in cells[1:]:
        assert sorted(re.findall(r'\{\d+\}', cell)) == placeholders, cells[0]
    rows.append(cells)
quote = lambda s: json.dumps(s, ensure_ascii=False)
cs = '// Generated by scripts/generate-localization.py; edit localization/ui.tsv.\nnamespace ScheduledClicker { internal static partial class L {\ninternal static readonly string[][] Catalog = new string[][] {\n'
swift = '// Generated by scripts/generate-localization.py; edit localization/ui.tsv.\nextension L {\nstatic let catalog: [[String]] = [\n'
for row in rows:
    cs += 'new string[] { ' + ', '.join(map(quote, row)) + ' },\n'
    swift += '[' + ', '.join(map(quote, row)) + '],\n'
cs += '};\n} }\n'
swift += ']\n}\n'
for path, content in [('ScheduledClicker/LocalizationCatalog.cs', cs), ('macOS/Sources/LocalizationCatalog.swift', swift)]:
    target = root / path
    if '--check' in sys.argv:
        assert target.read_text(encoding='utf-8') == content, f'Stale generated catalog: {path}'
    else:
        target.write_text(content, encoding='utf-8')
print(f'{len(rows)} keys: complete translations and matching placeholders for all five languages.')
